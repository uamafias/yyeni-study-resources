#!/usr/bin/env python3
"""Write exemplar/REPRESENTATIVE-SECTION.md: the 3.3.2-3.3.3 notes as rendered, and every card and
task in that slice with its labels, for a person to read before production is approved."""
import json, sys, glob, os
WS = 'work/nam-6116-nssco-2026'
notes = sys.argv[1]            # the notes file render_notes.py produced in the scratch run
items = json.load(open(f'{WS}/exemplar/3/learning-items/topic_3_items.json'))['items']
units = [json.load(open(p)) for p in sorted(glob.glob(f'{WS}/exemplar/3/content-units/*.json'))]
L = ['# Representative section: 3.3.2 Osmosis and 3.3.3 Active transport', '',
     'Generated by `planning/write_sample.py` from the exemplar. It covers all 10 objectives of the two '
     'sub-topics, written at the revised notes budget (`curriculum/notes-budget.json`):', '']
for u in units:
    L.append('- %s: %d words against a budget of %d–%d' % (u['title'], u['word_count'],
             u['word_budget']['min'], u['word_budget']['max']))
L += ['', 'Checks: installed in a scratch copy of the workspace with topic 3 cut to these objectives, '
      'run_checks.py reads PUBLISH. The only warning is C-18 (per-topic AO mix by item count, reported). '
      'C-39 passes. C-35, C-41 and C-43 do not apply (no graphical stimulus, depiction or practice text).', '',
      '---', '', '# Part 1: the notes, as a learner sees them', '']
body = open(notes).read().split('\n---\n', 1)[1]
L += [body.strip(), '', '---', '', '# Part 2: the cards and tasks', '']
for i in items:
    L += ['### %s' % i['item_id'],
          '*%s%s · %s · Bloom: %s · command word: %s · %s mark%s%s*' % (
              i['item_type'], (' / ' + i['subtype']) if i['subtype'] else '', '/'.join(i['assessment_objectives']),
              i['blooms_level'], i['command_word'] or '—', i['mark_tariff'], '' if i['mark_tariff'] == 1 else 's',
              (' · ' + i['misconception_entry']) if i.get('misconception_entry') else ''), '',
          '**Prompt.** ' + i['prompt'], '', '**Answer.** ' + i['canonical_answer'], '',
          '**Marking (proposed).**'] + ['- ' + g for g in i['marking_guidance']] + ['']
open(f'{WS}/exemplar/REPRESENTATIVE-SECTION.md', 'w').write('\n'.join(L))
print('written', len(items), 'items')
