def mapped(record):
    rules=MAP[(record['year'],record['paper_id'])]
    ref=record['question_ref']
    matches=[k for k in rules if ref==k or ref.startswith(k+'(') or ref.startswith(k+'#')]
    if not matches: raise ValueError(('No semantic mapping',record['evidence_id']))
    selector=max(matches,key=len)
    return rules[selector],selector
